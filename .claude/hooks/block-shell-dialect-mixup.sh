#!/usr/bin/env bash
# PreToolUse hook — חוסם תחביר PowerShell שנשלח בטעות לכלי Bash (ולהפך).
# חסימה = exit 2 + הסבר ב-stderr. Claude מקבל את ההסבר ומתקן, ולא "מנסה שוב אותו דבר".
#
# ── למה זה קיים ────────────────────────────────────────────────────────────────
# בסביבה הזו יש **שני** כלי-מעטפת: Bash (POSIX) ו-PowerShell. סשנים מערבבים ביניהם
# שוב ושוב — הכי נפוץ: here-string של PowerShell (@'...'@) בתוך כלי Bash, שנכשל בפרסינג.
# ‏`CLAUDE.md` כבר למד את זה פעם אחת, אבל בניסוח צר (חותמת-זמן: Get-Date מול date) —
# והמחלקה המשיכה לירות בצורה אחרת. כלל צר לא תפס את הצורה השלישית; hook כן.
#
# ⚠️ **וזה גילוי, לא מניעה.** ההוק תופס תחביר-שגוי לפני ההרצה; הוא לא הופך את הסשן
# לזהיר יותר. הפתרון האמיתי הוא לא לדחוף תוכן רב-שורתי דרך shell בכלל —
# ‏`Write` לקובץ, ואז להפנות לקובץ. ההודעה למטה אומרת את זה במפורש.
#
# ── עקרון-מילוט: fail-open ─────────────────────────────────────────────────────
# חילוץ-שדה שנכשל ⇒ לא חוסמים. אותו עיקרון של `protect-frozen-files.sh`: חסימת-שווא
# מלמדת לעקוף hooks, וזה גרוע מהחמצה נדירה.
#
# ── דיוק מכוון על פני כיסוי ────────────────────────────────────────────────────
# הרשימה מכילה **רק** ביטויים שאין להם שום שימוש לגיטימי ב-bash. במכוון **אין** בה
# `-Force` · `-Recurse` · `-ErrorAction` (מופיעים בטקסט חופשי) ולא `&&` (חוקי ב-bash).
# ⚠️ מגבלה ידועה: פקודת-bash שכותבת לקובץ **תוכן** שהוא PowerShell (למשל הוראות לישי)
# תיחסם בטעות. זה נדיר, וההודעה מסבירה איך לעקוף נכון (Write לקובץ).

INPUT=$(cat)

TOOL=$(printf '%s' "$INPUT" | grep -o '"tool_name"[[:space:]]*:[[:space:]]*"[^"]*"' | head -1 | sed 's/.*"\([^"]*\)"$/\1/')

# רק כלי Bash. PowerShell ושאר הכלים — לא נבדקים כאן.
[ "$TOOL" = "Bash" ] || exit 0

# חילוץ שדה הפקודה בלבד — לא כל הקלט (הבאג שתוקן ב-protect-frozen-files ב-08/07:
# בדיקה על כל הקלט גרמה חסימות-שווא משמות שהופיעו בהודעת-commit).
CMD=$(printf '%s' "$INPUT" | grep -o '"command"[[:space:]]*:[[:space:]]*"\(\\.\|[^"\\]\)*"' | head -1)
[ -n "$CMD" ] || exit 0   # fail-open

block() {
  cat >&2 <<'MSG'
🔀 תחביר PowerShell בכלי Bash — הפקודה לא הורצה.

אתה בכלי **Bash** (POSIX). מה שכתבת שייך ל-PowerShell ויישבר בפרסינג.

התרגום המהיר:
  @'…'@   ⇒  heredoc:  <<'EOF' … EOF
  Get-Date ⇒  date +"%d/%m/%Y %H:%M"
  $env:VAR ⇒  $VAR
  Set-Content / Out-File / New-Item ⇒  הכלי Write, או  > file
  Test-Path ⇒  [ -e path ]

🔴 ועדיף מכל תרגום — **אל תדחוף תוכן רב-שורתי דרך shell בכלל.**
כתוב אותו לקובץ עם הכלי `Write`, ואז הפנה לקובץ.
זה מבטל בבת-אחת: דיאלקט · בריחת-מרכאות · הרחבת-$ · גרשיים-הפוכים · CRLF.

(אם אתה באמת צריך להריץ PowerShell — יש כלי PowerShell נפרד.)
MSG
  exit 2
}

# ── הביטויים. רק כאלה שאינם תקינים ב-bash בשום הקשר. ──────────────────────────
# here-string של PowerShell — הצורה הנפוצה ביותר של התקלה.
printf '%s' "$CMD" | grep -q "@'" && block
printf '%s' "$CMD" | grep -q "@\\\\\"" && block          # @" — הווריאנט המרחיב
# cmdlets בתחילת פקודה או אחרי | ; && — כלומר במיקום של פועל, לא כטקסט.
printf '%s' "$CMD" | grep -Eq '(^|[;|&]|\\n)[[:space:]]*(Get-Date|Set-Content|Add-Content|Out-File|New-Item|Test-Path|Select-String|Where-Object|ForEach-Object|Remove-Item)\b' && block
# משתני-סביבה בסגנון PowerShell.
printf '%s' "$CMD" | grep -q '\$env:' && block

exit 0
