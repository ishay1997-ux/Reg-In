#!/usr/bin/env bash
# SessionStart hook — באנר-הקשר בפתיחת כל סשן (נוסף 07/07/2026 ערב; פרסונליזציה 08/07;
# קריסה למסלול-יחיד 22/07/2026 עם המעבר למפתח יחיד — זיהוי-המכונה ומסלול-המפתח-השני הוסרו).
# למה: "תמיד לדעת איפה אנחנו" היה עד עכשיו תלוי-משמעת (לקרוא STATUS ידנית);
# הבאנר הופך את זה למכני — ענף, הצעד הפעיל, ותזכורת-מקביליות.
# פלט ל-stdout בלבד; לעולם לא חוסם (exit 0 תמיד) — זה הקשר, לא שער.

cd "$(git rev-parse --show-toplevel 2>/dev/null || pwd)" || exit 0

BRANCH=$(git branch --show-current 2>/dev/null)
DIRTY=$(git status --porcelain 2>/dev/null | wc -l | tr -d ' ')

echo "📍 REG-IN | ענף: ${BRANCH:-?} | קבצים לא-מקומטים בעץ: ${DIRTY:-?}"

# חילוץ שורת "השלב הנוכחי" מ-STATUS.md (לוח-המצב היחיד) — מסלול יחיד מאז 22/07/2026.
# מציגים רק את נתיב-מדריך-השלב (לפני סוגר-הלינק), לא את כל שורת-ההסבר.
# אם כותרת "## המסלול" לא נמצאה (STATUS שינה מבנה) — fallback שסורק את הקובץ כולו.
if [ -f STATUS.md ]; then
  TRACK=$(awk 'index($0, "## המסלול"){f=1; next} f && /^\*\*השלב הנוכחי/{print; exit}' STATUS.md 2>/dev/null \
    | sed 's/\](.*//; s/\[//; s/\*\*//g')
  if [ -n "$TRACK" ]; then
    echo "🫵 הצעד הנוכחי: ${TRACK#השלב הנוכחי: }"
  else
    # fail-safe: הכותרת השתנתה — מציגים את השורה כפי שהיא, בלי לנחש
    grep '^\*\*השלב הנוכחי' STATUS.md 2>/dev/null | head -1 | sed 's/\](.*//; s/\[//; s/\*\*//g; s/^/🎯 /'
  fi
  grep -o '^> עודכן לאחרונה:.*' STATUS.md 2>/dev/null | head -1
  # דדליין-ההגשה + תוכנית פעילה (אם רשומה) — מצב-חי שמשפיע על טריאז' בקשות-שינוי
  grep -o '⏱️ \*\*דדליין-הגשה:[^*]*\*\*' STATUS.md 2>/dev/null | head -1 | sed 's/\*\*//g'
  grep -o '^- 🔧 \*\*תוכנית פעילה:.*' STATUS.md 2>/dev/null | head -1 | sed 's/^- /  /; s/\*\*//g'
fi

echo "ℹ️ קרא את CLAUDE.md + STATUS.md לפני עבודה. מפתח יחיד (ישי) — הכרעות §7/עיצוב תמיד שלו (כלל 1). סשן שני במקביל לכותב? Plan Mode או P8 — כלל 16."
exit 0
