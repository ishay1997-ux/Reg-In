// ✏️ ישי 14/10 ~18:0x ("צבעוני מדי ולא מקצועי... בעיה נרחבת בכל המערכת... תעשה בקטנה"): רקעים רכים
// (‎-50 במקום ‎-100/‎-200) לכל הטונים — אותה משמעות, פחות רעש. מצבי-סיום עברו לאפור ב-`projects.js`.
const TONES = {
  ok: 'bg-green-50 text-green-700',
  teal: 'bg-teal-50 text-teal-700',
  muted: 'bg-slate-100 text-slate-500',
  warn: 'bg-amber-50 text-amber-800',
  outline: 'bg-slate-100 text-slate-600 border border-slate-200',
  dashed: 'bg-slate-100 text-slate-500 border border-dashed border-slate-300',
  // 🔴 `danger` — אדום, ונוסף למען מודול 8 (‏27/08/2026). **הרחבה מאושרת, לא המצאה:** ה16
  // מחייבת אדום לציון-משוב מתחת ל-3, והמוקאפ המאושר `02_closing_window_approved.html`
  // מכריז עליו במפורש (`.tag.danger{background:var(--red100); color:var(--red700)}`, שורה 164,
  // ובנספח "מה הכרעתי לבד" ④: *"הרחבתי בטוקנים קיימים בלבד — לא צבע חדש"*).
  // ⚠️ **ולמה הוא נוסף כאן ולא במסך שצורך אותו:** בלעדיו `scoreTag()` מחזירה `tone: 'danger'`,
  // והשורה למטה (`?? TONES.muted`) הייתה מציגה אותו **אפור, בלי שגיאה** — כלומר "טעון בירור"
  // היה נראה בדיוק כמו סטטוס נייטרלי. זה בדיוק כשל-ההאפרה שההערה של `PROJECT_STATUS_TONES`
  // מזהירה ממנו, ונתפס ע"י בודק בפזה 2 לפני שנבנה ולו מסך אחד.
  danger: 'bg-red-50 text-red-700',
}

import { PROJECT_STATUS_TONES } from '@/lib/projects'

// ⚠️ `לא זמינה DD/MM–DD/MM` **אינו כאן במכוון** — התווית שלו דינמית (היא נושאת תאריכים),
// ולכן הקורא מעביר `tone="warn"` במפורש. מפתח קבוע היה מחייב אותה להיות מחרוזת קבועה.
const TONE_BY_LABEL = {
  // מצב הדיילת
  פעילה: 'ok',
  מושבתת: 'dashed',
  // ששת סטטוסי-השיבוץ (`spec.md §1.1`) + שתי הנגזרות
  'אושרה סופית': 'ok',
  'אישרה זמינות': 'teal',
  'ממתינה למענה': 'muted',
  סירבה: 'outline',
  שוחררה: 'dashed',
  'ביטלה אחרי אישור': 'muted',
  'פג תוקף': 'warn',
  הושלם: 'muted', // מצב-סיום: אין מה לעשות ⇒ בלי צבע (ישי 14/10)
  // 🔴 שמונת סטטוסי-הפרויקט (מודול 6) — ב-spread מ-`src/lib/projects.js`, לא בהקלדה
  // מחדש: מקור-אמת אחד לתווית-וטון, כי תווית שהוקלדה כאן שוב ונבדלת בתו אחד נופלת
  // בשקט ל-`muted` (למטה, `?? TONES.muted`) — אפור שזהה-בייט לטון של סטטוס אמיתי,
  // כלומר בלתי-נראה על המסך. שם השומר שצועק במקום להאפיר: `resolveProjectTone`.
  ...PROJECT_STATUS_TONES,
}

// label: התווית **כפי שהיא נכתבת על המסך** · tone: דריסה, נדרשת רק לתוויות דינמיות.
// 🚫 תווית לא-מוכרת מקבלת `muted` ולא נופלת — צבע שגוי עדיף על מסך ריק, והתווית עצמה
// ממילא נכונה כי היא מגיעה מ-`src/lib/hostesses.js`.
export default function StatusTag({ label, tone, testId }) {
  if (!label) return null

  const resolved = TONES[tone ?? TONE_BY_LABEL[label]] ?? TONES.muted

  return (
    <span
      className={`inline-block whitespace-nowrap rounded-full px-2.5 py-0.5 text-xs font-semibold ${resolved}`}
      data-testid={testId}
    >
      {label}
    </span>
  )
}
