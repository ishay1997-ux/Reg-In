// תג-סטטוס משותף — הצורה היחידה של "גלולה צבועה שאומרת באיזה מצב הדבר הזה נמצא".
//
// למה רכיב ולא מחלקות מועתקות: התג מופיע ב-**שישה** מתוך שמונת המשטחים המאושרים של מודול 4
// (מאגר · Smart Match · תפריט-השורה · כרטיס-הדיילת · חלון-העריכה · הדף הציבורי), וזה בדיוק
// הסף שהמדריך קבע ל"משותף". אותו לקח של `StatTile`: אריח שהוגדר פעמיים **סטה** בפועל —
// וכאן הסטייה מסוכנת יותר, כי צבע הוא **משמעות**: ירוק אומר "סגור, אין מה לעשות" ואם אותו
// סטטוס ייצבע ענבר במסך אחר, המנהלת תפעל על שורה שלא צריכה אותה.
//
// 🎨 הצבעים **נקראו מתוך המוקאפים המאושרים** (`grep` על `.st`/`.stp` בקבצי `approved/`),
// לא נבחרו בעין ולא הומצאו. המיפוי למטה הוא תרגום 1:1 שלהם.
//
// 🔴 **המפתח הוא התווית המוצגת, לא ערך-ה-enum** — כי `assignmentDisplayStatus()` מחזירה
// תווית, וששת הסטטוסים + שתי הנגזרות (`פג תוקף`, `הושלם`) חיים באותו אוצר-מילים נעול
// (`spec.md §1.1`). מפתוח לפי ה-enum היה מחייב את הקורא לדעת גם את הערך וגם את התווית.

// טון ⇒ המחלקות שלו. `warn` הוא ענבר: **לא הצלחה ולא שגיאה — אזהרת-היגיינה** (זו המשפחה
// של "פג תוקף" ושל "לא זמינה", וכך נומקה במוקאפ 03 במפורש).
const TONES = {
  ok: 'bg-green-100 text-green-700',
  teal: 'bg-teal-100 text-teal-700',
  muted: 'bg-slate-100 text-slate-500',
  warn: 'bg-amber-200 text-amber-800',
  outline: 'bg-slate-100 text-slate-600 border border-slate-200',
  dashed: 'bg-slate-100 text-slate-500 border border-dashed border-slate-300',
}

// ⚠️ `לא זמינה DD/MM–DD/MM` **אינו כאן במכוון** — התווית שלו דינמית (היא נושאת תאריכים),
// ולכן הקורא מעביר `tone="warn"` במפורש. מפתח קבוע היה מחייב אותה להיות מחרוזת קבועה.
const TONE_BY_LABEL = {
  // מצב הדיילת
  פעילה: 'ok',
  מושבתת: 'dashed',
  // ששת סטטוסי-השיבוץ (`spec.md §1.1`) + שתי הנגזרות
  'אושרה סופית': 'ok',
  'אישרה זמינות': 'teal',
  'ממתינה למענה': 'muted',
  סירבה: 'outline',
  שוחררה: 'dashed',
  'ביטלה אחרי אישור': 'muted',
  'פג תוקף': 'warn',
  הושלם: 'ok',
}

// label: התווית **כפי שהיא נכתבת על המסך** · tone: דריסה, נדרשת רק לתוויות דינמיות.
// 🚫 תווית לא-מוכרת מקבלת `muted` ולא נופלת — צבע שגוי עדיף על מסך ריק, והתווית עצמה
// ממילא נכונה כי היא מגיעה מ-`src/lib/hostesses.js`.
export default function StatusTag({ label, tone, testId }) {
  if (!label) return null

  const resolved = TONES[tone ?? TONE_BY_LABEL[label]] ?? TONES.muted

  return (
    <span
      className={`inline-block whitespace-nowrap rounded-full px-2.5 py-0.5 text-[11px] font-semibold ${resolved}`}
      data-testid={testId}
    >
      {label}
    </span>
  )
}
