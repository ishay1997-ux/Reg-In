// ⚠️ **חוזה-הקורא: השאילתה חייבת סדר-מלא (`.order()` עם שובר-שוויון ייחודי).** דפדוף בלי סדר
// יציב מחזיר שורה פעמיים ומדלג על אחרת בין עמודים, בלי שגיאה — אותו סוג כשל שקט בדיוק.
// ‏`buildQuery` היא פונקציה שמחזירה בילדר **טרי** בכל קריאה, כי `.range()` משנה את הבילדר.
const PAGE_SIZE = 1000

export async function fetchAll(buildQuery, { pageSize = PAGE_SIZE } = {}) {
  const rows = []
  for (let from = 0; ; from += pageSize) {
    const { data, error } = await buildQuery().range(from, from + pageSize - 1)
    if (error) return { data: null, error }
    rows.push(...(data ?? []))
    if ((data?.length ?? 0) < pageSize) return { data: rows, error: null }
  }
}
