// הקורא המשותף של טבלת `params` — **חוצה-מודולים, ושייך לטבלה שאין לה מודול-בעלים.**
//
// למה כאן ולא ב-`src/lib/` ולא בתוך מודול (אותו נימוק בדיוק כמו `src/api/email.js`):
//   · `src/lib/` הוא **טהור** — אף קובץ בו אינו מייבא את `supabaseClient`, וזה מה שמאפשר
//     לבדוק בו כללים בלי סביבה. שאילתה הייתה שוברת את זה.
//   · `src/modules/NN_*/api.js` הוא **פר-מודול**, ו-`params` אינה של אף מודול: מ2, מ3, מ4,
//     מ5, מ6, מ8 ומ9 קוראים ממנה באותה מידה. עותק פר-מודול היה מתפצל בשקט ביום שהטיפול
//     בפרמטר-חסר משתנה.
// ⛔ המסקנה המעשית: מסך שצריך ערך-פרמטר ואין לו כבר טוען-פרמטרים משלו — מייבא **מכאן**.
//
// ⚠️ מה זה **אינו** מחליף: טוען-פרמטרים של מודול שנשלף **יחד עם שאר נתוני-המסך**
// (`getQuoteScreenParams` במ3, `getCustomerScreenParams` במ2) נשאר במקומו — מעבר לכאן היה
// מוסיף סיבוב-רשת בלי תמורה. **הוא כן נעטף כשאין לו הצדקה כזו:** `getHostessScreenParams`
// (מ4) הפכה לעטיפה דקה של הפונקציה הזו, כי היא הייתה שאילתה עצמאית שהחזירה מפה **חלקית**
// בשקט — כלומר בדיוק ההתנהגות שהקובץ הזה נוצר כדי לסגור.

import { supabase } from '@/supabaseClient'
import { toError } from '@/lib/apiError'

// ערכי-פרמטרים לפי שם, כמפה `{ שם: ערך }`.
//
// 🔴 **שם שלא חזר מהמסד — או שחזר ריק — זורק, ולעולם אינו מקבל ברירת-מחדל.** זה החוזה
// כולו, וזו הסיבה שהפונקציה קיימת בכלל: הערכים שנקראים דרכה הם **ספים עסקיים** (מתי זימון
// פג · מתי אירוע דחוף · מתי משוב דורש בירור), וסף מומצא מייצר מסך שנראה תקין לחלוטין
// ומבוסס על מספר שאיש לא הכריע. מסך שאומר "לא ניתן לטעון" עדיף על מסך ששקט ושוגה.
// 🚨 ובמסד הזה זה אינו תיאורטי: קריאה שנחסמה ע"י RLS מחזירה **אפס שורות עם `error: null`**,
// כלומר "הצלחה ריקה" שנראית בדיוק כמו "הפרמטר לא קיים". שתיהן חייבות להישמע, ולכן הבדיקה
// היא על **מה שחזר** ולא רק על `error`.
//
// ⚠️ ‏`param_value` הוא `text` לכל סוג — **הפענוח הוא של הקורא** (`optionalNumber`
// שב-`src/lib/hostesses.js`, `paramBoolean` שב-`src/lib/smartMatch.js`). החזרת מספר מכאן
// הייתה מחייבת את הקורא לדעת מראש איזה סוג כל שם נושא, ומכריחה סוג אחד על תבניות-מייל.
//
// 🔗 התקדימים שהניסוח נגזר מהם, מילה-במילה: `getParamValue` (`06_projects/closingApi.js`)
//    להודעת-היחיד, ו-`getEmailTemplate` (`src/api/email.js`) לעטיפת-השגיאה ולקוד `PGRST116`.
export async function getParamValues(names) {
  // כפילות בשמות מסוננת כאן ולא אצל הקורא: מסך שמאחד שתי רשימות-שמות אינו צריך לדעת
  // שהאיחוד עלול לכפול, וכפילות הייתה מייצרת הודעת-חוסר שמונה את אותו שם פעמיים.
  const wanted = [...new Set(names ?? [])]
  if (wanted.length === 0) return {}

  const { data, error } = await supabase
    .from('params')
    .select('param_name, param_value')
    .in('param_name', wanted)
  if (error) throw toError(error, 'שגיאה בטעינת הגדרות המערכת.')

  const values = Object.fromEntries((data ?? []).map((row) => [row.param_name, row.param_value]))

  // מחרוזת-רווחים נחשבת חסרה: `Number('   ')` הוא **0** (המלכודת המתועדת של
  // `optionalNumber`), כלומר שורה ריקה במסד הייתה נקראת כ"סף 0" ומכשירה הכול.
  const missing = wanted.filter((name) => {
    const value = values[name]
    return value === null || value === undefined || String(value).trim() === ''
  })
  if (missing.length > 0) {
    // כל השמות החסרים בהודעה אחת, ולא רק הראשון: המשתמשת שתפתח את מסך ההגדרות צריכה
    // לדעת כמה שורות להשלים, לא לגלות אותן אחת-אחת בסבבי-רענון.
    const quoted = missing.map((name) => `"${name}"`).join(', ')
    throw toError(
      { code: 'PGRST116' },
      missing.length === 1
        ? `הפרמטר ${quoted} חסר בהגדרות המערכת.`
        : `הפרמטרים ${quoted} חסרים בהגדרות המערכת.`,
    )
  }

  return values
}
