export const ONBOARDING_LEVEL = Object.freeze({ CLEAN: 0, POINTERS: 1, GUIDED: 2 })

// ערך-הטבלה של "כבוי"/"דלוק" במתגים (כן/לא ⇒ 0/2 — 28⑭; קריאה: > 0 = דלוק).
export const ONBOARDING_OFF = ONBOARDING_LEVEL.CLEAN
export const ONBOARDING_ON = ONBOARDING_LEVEL.GUIDED

export function isValidOnboardingLevel(value) {
  return (
    Number.isInteger(value) && value >= ONBOARDING_LEVEL.CLEAN && value <= ONBOARDING_LEVEL.GUIDED
  )
}

export const ONBOARDING_COPY = Object.freeze({
  // המתג עצמו, בלשונית "העדפות והתראות" — הדוגמה המחייבת מהתוכנית (§4 שלב 0).
  'onboarding.self': {
    guided:
      'ההסברים נועדו לשבוע-שבועיים הראשונים. כשתרגישי שאת כבר לא קוראת אותם — כבי אותם, והמערכת תישאר בדיוק אותה מערכת, רק שקטה יותר.',
  },
})

// מחזירה את רשומת-הקופי של המפתח, או null כשאין — הקורא (Hint) מחליט מה לעשות עם null.
export function getOnboardingCopy(id) {
  return Object.prototype.hasOwnProperty.call(ONBOARDING_COPY, id) ? ONBOARDING_COPY[id] : null
}
