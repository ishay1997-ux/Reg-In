// סקירת-הקוד — הפונקציה הייתה משוכפלת **זהה-בייט** בשלושה קבצים: 01_auth/pricesApi.js,
// 02_customers/api.js, 03_quotes/api.js).
//
// למה זריקה ולא החזרת {error}: קריאה שנכשלת היא חריגה אמיתית ולא זרימה רגילה, ו-throw
// מאפשר ל-UI לעטוף ב-try/catch אחד. למה `code` משומר: ה-UI מבחין במקרים ידועים (23505 =
// הפרת-unique על ח"פ/מק"ט, P0001 = טריגר-הנעילה) בלי שמבנה אובייקט-השגיאה של Supabase
// יזלוג לכל קורא.

export function toError(error, fallbackMessage) {
  const e = new Error(fallbackMessage)
  e.code = error?.code
  e.cause = error
  return e
}

// 🚨 הכשל השקט המרכזי של הפרויקט (`src/CLAUDE.md`): כתיבה שנחסמה ע"י RLS חוזרת מ-PostgREST
// כ-**0 שורות עם `error: null`** — כלומר כפתור-שמירה שמציג "נשמר" ולא שינה כלום. אין כלל-lint
// שאוכף את הבדיקה הזו, ולכן היא חייבת להיות זולה לכתיבה: זה מה שהעוטף הזה קיים בשבילו.
// ⚠️ הקוד סינתטי במכוון — הוא לא הגיע מהמסד, הוא **המסקנה שלנו** מ-0 שורות.
export const RLS_DENIED_CODE = 'RLS_DENIED'

// מאמת שכתיבה אכן נגעה בשורה. `message` נאמר למשתמש, ולכן הוא פר-אתר-קריאה ולא גנרי —
// "אין הרשאה לעדכן מוצר זה" מול "אין הרשאה לשמור מדרגות מחיר" הן שתי פעולות שונות.
// ⚠️ 0 שורות אינו תמיד RLS: הוא גם "השורה לא קיימת". שתי האפשרויות חייבות להישמע ולא
// להיראות כהצלחה, ולכן הניסוח באתרי-הקריאה הוא "ייתכן שאין לך הרשאה" כשהוא דו-משמעי.
export function assertRowsAffected(data, message) {
  if (!data || data.length === 0) throw toError({ code: RLS_DENIED_CODE }, message)
  return data
}
