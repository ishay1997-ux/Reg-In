/**
 * `key` ⇐ ההרשאה שנדרשת כדי שהעמודה תיכנס לקובץ.
 *
 * 📊 **נמדד 22/09/2026, וזו השרשרת המלאה:**
 * `reportsCatalog.js:209` — `OPEN_LEVELS = new Set(['edit','view'])` ⇒ משתמשת עם `view`
 * פותחת את לשונית-הדיילות · ה-RPC מכניס אותה
 * (`20260916052359_module11_f_rpcs_hostesses.sql:964` — `assert_module_permission('דיילות',
 * array['edit','view'])`) · והוא מכריז את `hourly_rate` כעמודת-טבלה
 * (`20260917005500_module11_j1_rpc_round4.sql:2156`) **בלי שום סימון רגישות.**
 * ⇒ היא מריצה "איכות מול עלות", מייצאת, והתעריף של כל דיילת בקובץ כמספר.
 *
 * ⚠️ **מוסיפים לכאן בצמצום.** רישום-יתר מרוקן דוחות-ניהול לגיטימיים
 * והוא כשל בפני עצמו. **עמודה נכנסת רק כשיש מסך שמסתיר את אותו נתון.**
 */
// 🚫 **אינו מיוצא בכוונה** — `allowsColumn` היא הדלת היחידה החוצה. ייצוא בלי צרכן מפיל
// את `knip`, והתיקון הנכון הוא לצמצם את ה-API ולא להוסיף `ignore` (הכרעת-ישי 29/07/2026).
const SENSITIVE_COLUMNS = {
  // התעריף האישי של דיילת. המסך מסתיר אותו ללא `edit` — והקובץ חייב לנהוג זהה.
  hourly_rate: { module: 'דיילות', levels: ['edit'] },
}

/**
 * האם ההרשאות שביד מספיקות לעמודה הזו.
 *
 * 🔴 **נופל סגור בשלושה מצבים, וזו כל הנקודה:** עמודה רשומה ואין מפת-הרשאות
 * · אין ערך למודול · הערך אינו ברשימת-המותרים ⇒ **מוסתרת.**
 * מפתח שאינו ברשם מותר — אחרת 16 הדוחות הקיימים היו מתרוקנים בשקט.
 */
export function allowsColumn(key, permissions) {
  const rule = SENSITIVE_COLUMNS[key]
  if (!rule) return true
  const level = permissions?.[rule.module]
  return typeof level === 'string' && rule.levels.includes(level)
}
