// 🚫 **אינו מיוצא בכוונה** — `allowsColumn` היא הדלת היחידה החוצה. ייצוא בלי צרכן מפיל
// את `knip`, והתיקון הנכון הוא לצמצם את ה-API ולא להוסיף `ignore` (הכרעת-ישי 29/07/2026).
const SENSITIVE_COLUMNS = {
  // התעריף האישי של דיילת. המסך מסתיר אותו ללא `edit` — והקובץ חייב לנהוג זהה.
  hourly_rate: { module: 'דיילות', levels: ['edit'] },
  // 🔴 **אותו נתון, מפתח שני — וזה בדיוק המצב שרשם לפי מפתח עלול לפספס.**
  // װ`hourly_rate_snapshot` הוא התעריף שהוקפא בשיבוץ (`04_hostesses/api.js:653`),
  // והוא מוצג היום כ-`תעריף מוקפא` (`06_projects/TeamTab.jsx:503` · `:527`).
  // 🔑 **שלוש תוויות לאותו שדה** — `שכר שעתי` (מ4) · `תעריף שעתי` (ה-RPC) ·
  // `תעריף מוקפא` (מ6). **חיפוש לפי תווית מפספס שניים מהשלושה.**
  // ⚠️ **ולמה הוא נרשם לפני שיש לו צרכן בייצוא:** מפתח שאינו ברשם עובר במכוון,
  // ולכן הוא היה **מיוצא בשקט** ביום שמסך-הפרויקטים יחובר — **והוא המסך הבא בתור.**
  hourly_rate_snapshot: { module: 'דיילות', levels: ['edit'] },
}

/**
 * דפוסי-מפתח של **שכר פר-אדם**, לשימוש הבדיקה שסורקת את קבצי-המיגרציה.
 *
 * 🔴 **למה זה קיים, וזו הנקודה שהסבב הקודם פיספס:** רשם ממופתח מגן מפני
 * מפתח שהוא **מכיר**, ועובר בשתיקה על מפתח חדש. **מיגרציה עתידית שתחשוף
 * שדה-שכר תחת שם שלישי תשאיר את כל הבדיקות ירוקות** — אלא אם משהו סורק בפועל.
 * ⇒ `exportSensitiveColumns.test.js` קורא את קבצי-המיגרציה מהדיסק ונופל על כל התאמה
 * שאינה רשומה. **זה מנגנון; הערה "הועתק מהמיגרציה" אינה מנגנון.**
 *
 * ⚠️ **והוא מכוון לשכר-פר-אדם בלבד, ולא לכל `money`:** עמודות-כסף מצרפיות
 * (הכנסה · רווח · עלות-פרויקט) הן לב דוחות-הניהול, ורישום גורף היה מרוקן אותם.
 */
export const PERSON_RATE_KEY_PATTERN =
  /^(hourly_rate|.*_hourly_rate|hourly_rate_.*|.*_wage|wage_.*|.*_salary|salary_.*)$/

/**
 * האם ההרשאות שביד מספיקות לעמודה הזו.
 *
 * 🔴 **נופל סגור בשלושה מצבים, וזו כל הנקודה:** עמודה רשומה ואין מפת-הרשאות
 * · אין ערך למודול · הערך אינו ברשימת-המותרים ⇒ **מוסתרת.**
 * מפתח שאינו ברשם מותר — אחרת 16 הדוחות הקיימים היו מתרוקנים בשקט.
 */
export function allowsColumn(key, permissions) {
  const rule = SENSITIVE_COLUMNS[key]
  if (!rule) return true
  const level = permissions?.[rule.module]
  return typeof level === 'string' && rule.levels.includes(level)
}
