// מילוי תבנית מ-`params`. `replacements` הוא מפה של placeholder ⇒ ערך, למשל
// `{ '[שם_איש_קשר]': 'רון גל' }` — המודול השולח הוא שיודע אילו placeholders יש בתבנית שלו.
//
// ⚠️ שני כללי-בטיחות שאינם קוסמטיים:
// (1) תבנית חסרה ⇒ מחרוזת ריקה, ולא "מייל בלי גוף". פרמטר שלא נטען הוא תקלה, ומייל ריק
//     שנשלח ללקוח גרוע ממייל שלא נשלח.
// (2) split/join ולא regex — התבניות מכילות סוגריים מרובעים, שהם תווים מיוחדים ב-regex.
//     בנוסף זה מחליף **כל** המופעים, כולל placeholder שחוזר פעמיים באותה תבנית.
// שדות-תבנית שהקוד **אינו** מכיר. מוחזרים בשמם כדי שההודעה למשתמש תוכל להצביע על מה
// לתקן, ולא רק לומר "נכשל".
//
// ⚠️ **סורקים את התבנית ולא את התוצאה — וזה ההבדל בין הגנה לבאג.** כל לקוחות-הדמו נקראים
// `… בע"מ [דמו]`, ולקוח בלי איש-קשר נופל לשם-החברה; סריקה על הגוף **אחרי** המילוי הייתה
// מזהה את `[דמו]` כשדה-לא-מוכר וחוסמת שליחה לכל לקוחות-הדמו. ערכים מוזרקים הם דאטה
// לגיטימית שמותר לה להכיל סוגריים; רק התבנית היא חוזה.
//
// ⚠️ הביטוי אינו חוצה שורות (`[^\]\n]`), כדי ששורה שנפתחת בסוגר ולא נסגרת לא "תבלע"
// את כל הפסקה שאחריה.
const PLACEHOLDER_PATTERN = /\[[^\]\n]+\]/g

export function findUnknownPlaceholders(template, replacements) {
  if (!template) return []
  const known = new Set(Object.keys(replacements ?? {}))
  const found = String(template).match(PLACEHOLDER_PATTERN) ?? []
  return [...new Set(found)].filter((token) => !known.has(token))
}

// ⚠️ **מסרב כשיש שדה לא-מוכר** (מחזיר ריק, ולכן `buildEmailPayload` יחזיר null והשליחה
// לא תצא). למה חסימה ולא אזהרה: §7.70 קובע שבמודול 3 עורכים פרמטרים דרך ה-Table Editor,
// כלומר תוספת-שדה לתבנית היא תרחיש מתוכנן — ומייל שיוצא ללקוח עם `[שם_חברה]` גולמי הוא
// נזק בלתי-הפיך מול לקוח משלם, בעוד שכפתור חסום עם הודעה ברורה נפתר בחצי דקה.
export function fillEmailTemplate(template, replacements) {
  if (!template) return ''
  if (findUnknownPlaceholders(template, replacements).length > 0) return ''

  return Object.entries(replacements ?? {}).reduce(
    (text, [token, value]) => text.split(token).join(String(value ?? '')),
    template,
  )
}

// טקסט-פשוט מ-`params` ⇒ גוף-מייל HTML **בעברית**. שלוש בעיות נפרדות נפתרות כאן יחד,
// ובכוונה באותה פונקציה: כל אחת מהן נתפסה בגוף-מייל אמיתי אצל ישי (30/07/2026), ופיצולן
// לשלוש פונקציות היה מאפשר לקורא עתידי לקבל אחת בלי השתיים האחרות.
//
// (1) **מעבר-שורה:** התבניות הן טקסט פשוט, ומודול-הדואר שולח HTML — שבו `\n` חסר משמעות.
//     בלי ההמרה חמש שורות התבנית נקראות אצל הלקוח כפסקה אחת רצה.
// (2) **כיווניות:** ⚠️ **המופע החמישי של באג-הכיווניות בפרויקט, והראשון מחוץ למסך.** גוף
//     עברי בלי `dir="rtl"` מוצג LTR אצל הלקוח, והפיסוק (פסיק, נקודה) נופל בצד הלא-נכון.
//     הפתרון הוא **מבני** ולא משמעת: הפונקציה פולטת עטיפה+תוכן יחד, בדיוק כמו `Money`
//     ו-`LtrFieldGroup` במסכים — ר' `src/CLAUDE.md`.
// (3) **הברחת תווים:** הערכים המוזרקים מגיעים מהמסד (שם-חברה, שם-אירוע); שם עם `&` או `<`
//     היה שובר את גוף המייל.
//
// ⚠️ סדר הפעולות load-bearing: **מברחים את התוכן קודם, ורק אחר-כך מוסיפים תגים משלנו.**
// בסדר ההפוך ה-`<br>` וה-`<div>` היו מוברחים בעצמם ומודפסים ללקוח כטקסט.
export function plainTextToEmailHtml(text) {
  if (!text) return ''
  const escaped = String(text)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/\r\n|\r|\n/g, '<br>')
  // ‏style ולא רק dir: חלק מלקוחות-הדואר מתעלמים מ-attribute ומכבדים inline-style.
  return `<div dir="rtl" style="text-align:right">${escaped}</div>`
}

// גוף-המשלוח שנשלח לפונקציית-השרת. `null` מוחזר כשחסר רכיב הכרחי — כדי שלא תישלח לעולם
// הודעה בלי נמען, בלי גוף או בלי הקובץ המצורף. הבדיקה כאן היא **הרשת האחרונה**: תנאי-הסף
// כבר נבדקו במסך (`emailSendDisabledReason`), ולכן null כאן מסמן תקלה ולא מצב-משתמש צפוי.
export function buildEmailPayload({ to, subject, body, filename, attachmentBase64 } = {}) {
  const recipient = to?.trim() ?? ''
  if (!recipient || !body || !attachmentBase64) return null

  return {
    to: recipient,
    subject: subject ?? '',
    // ⚠️ ההמרה ל-HTML **ולכיווניות** קורית כאן ולא בקורא: זו נקודת-המעבר היחידה בין
    // הטקסט-הפשוט שבמסד לבין תעבורת-ה-HTML של מודול-הדואר. קורא שישכח אותה שולח ללקוח
    // פסקה רצה בכיווניות הפוכה — שני פגמים שנתפסו בפועל בגוף-מייל אמיתי.
    body: plainTextToEmailHtml(body),
    filename,
    pdf_base64: attachmentBase64,
  }
}

// הסיבה שכפתור-השליחה מושבת, כטקסט ה-title (אותה תבנית כמו `disabledSendReason` בפאנל-השיווק
// של מודול 2). **סדר-הקדימויות הוא החלטה, לא סידור שרירותי:**
// (1) הרשאה קודמת לכל — אין טעם להנחות מישהו לתקן כתובת אם ממילא לא יורשה לשלוח;
// (2) חוסר-כתובת ואחריו כתובת-פגומה — שתיהן נפתרות בכרטיס-הלקוח, אבל הפעולה שונה
//     ("להוסיף" מול "לתקן"), ולכן שתי הודעות ולא אחת;
// (3) תבנית חסרה אחרונה — תקלת-הגדרות-מערכת, לא משהו שמשתמש-קצה יכול לתקן.
// ⚠️ בדיקת-הפורמט חוסמת **לפני** היציאה: ישי דיווח (מפרויקט 710) שכתובת פגומה אחת מפילה את
// מודול-המייל ב-Make ומשביתה את התרחיש כולו. עדיף לחסום בכפתור מלגלות מ-Make שנכשל.
export function emailSendDisabledReason({ email, template, canEdit = true } = {}) {
  if (!canEdit) return 'אין לך הרשאה לשלוח הצעות'
  const trimmed = email?.trim() ?? ''
  if (!trimmed) return 'אין כתובת מייל לאיש הקשר'
  if (!EMAIL_REGEX.test(trimmed)) return 'כתובת המייל של איש הקשר אינה תקינה'
  if (!template?.trim()) return 'תבנית המייל אינה מוגדרת במערכת'
  return ''
}

