// ⚠️ **שלושה ולא שניים**, וזו ההבחנה הקלה-לפספס במנוע הזה: כשפסק-זמן או תקלת-רשת קטעו את
// התשובה, המייל **אולי כן נשלח**. לומר "לא נשלח" יגרום לשליחה כפולה ללקוח אמיתי; לומר
// "נשלח" יסתיר הצעה שאיש לא קיבל. לכן מצב שלישי שאומר בדיוק את מה שידוע.
export const EMAIL_SEND_RESULT = { SENT: 'sent', FAILED: 'failed', UNKNOWN: 'unknown' }

// סיווג השגיאה שנתפסה לאחד משלושת המצבים. מופרד מהקומפוננטה כדי שיהיה בר-בדיקה בלי דפדפן.
export function classifySendError(error) {
  if (error?.message === 'TIMEOUT' || error?.name === 'FunctionsFetchError') {
    return EMAIL_SEND_RESULT.UNKNOWN
  }
  return EMAIL_SEND_RESULT.FAILED
}

// ההודעה שמוצגת למשתמש לכל מצב. **הודעת-כשל היא פעולה ולא דיווח** (בקשת-ישי 30/07): היא
// אומרת מה לעשות עכשיו. הודעת "לא ידוע" מפנה לבדיקה **לפני** ניסיון חוזר, כדי שההגנה מפני
// שליחה-כפולה לא תיפרץ בדיוק ברגע שהיא הכי נחוצה.
export function sendResultMessage(result) {
  switch (result) {
    case EMAIL_SEND_RESULT.UNKNOWN:
      return 'לא התקבל אישור שהמייל נשלח. בדוק בתיבת "נשלחו" שלך לפני שליחה חוזרת, כדי לא לשלוח פעמיים.'
    case EMAIL_SEND_RESULT.FAILED:
      return 'ההצעה לא נשלחה. לחץ "שליחת ההצעה במייל" שוב, או הורד את הקובץ ושלח ידנית.'
    default:
      return ''
  }
}

