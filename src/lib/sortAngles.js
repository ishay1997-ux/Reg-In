// מיון עולה עם `null` **בסוף** — נתון חסר לעולם לא מתחזה ל"הכי טוב".
function ascending(getter) {
  return (a, b) => {
    const left = getter(a)
    const right = getter(b)
    if (left === null || left === undefined) return right === null || right === undefined ? 0 : 1
    if (right === null || right === undefined) return -1
    return left - right
  }
}

const COMPARATORS = {
  // 🔴 **הציון המעוגל של `rankCandidates` — יורד.** שובר-השוויון שב-`sortByAngle` הוא אותו
  // `tieBreak` שהדירוג משתמש בו, ולכן העדשה הזו מחזירה **בדיוק** את סדר `rankCandidates`.
  recommended: (a, b) => Number(b.score ?? 0) - Number(a.score ?? 0),
  proximity: ascending((c) => c.distanceKm),
  customer: (a, b) => Number(b.workedForCustomerCount ?? 0) - Number(a.workedForCustomerCount ?? 0),
  // 🐞 **עד 25/09/2026 מיינה לפי `averageResponseHours` — שדה שאף קוד לא יצר.** ההשוואה יצאה
  // "שוויון" אצל כולן, והסדר נקבע בשובר-השוויון בלבד: **הגרלה קבועה תחת הכותרת "תענה הכי
  // מהר"**, ודווקא ב-72 השעות שבהן היא ברירת-המחדל (אודיט השיבוץ-החכם, פער 2).
  fastest: ascending((c) => c.medianResponseHours),
  cheapest: ascending((c) => Number(c.hourly_rate)),
}

// ‏`hasResponseTimes` מגיע מהמסך — **האם למועמדות של האירוע הזה** יש זמן-תגובה מדוד — ולא
// נגזר כאן: הקובץ הזה טהור ואינו יודע דבר על המסד.
// ⚠️ **המועמדות, לא החברה:** עד 25/09/2026 המסך בדק "יש `responded_at` בשורה כלשהי במסד",
// והכפתור נדלק גם כשלאף מועמדת ברשימה לא היה זמן — וזה מה שהשאיר את ההגרלה חיה.
export function isAngleAvailable(angle, { hasResponseTimes } = {}) {
  return angle === 'fastest' ? Boolean(hasResponseTimes) : true
}

// ✏️ **הכרעת-ישי 25/09/2026 — ברירת-המחדל היא "המלצת המערכת".** ‏`§11.7` המקורי אמר
// *"תענה הכי מהר"* **רק** כשהאירוע קרוב מ-72 שעות · אחרת *"קרבה"*; החלק השני הוחלף בהמלצה,
// והחלק הראשון נשאר — ההמלצה שישי אישר (פער 1 (א)) אומרת במפורש ש*"'תענה הכי מהר' נשארת
// ברירת-המחדל ב-72 השעות"*: *"האירוע מחר ואין זמן לחכות"* (`spec.md` §ארבע הזוויות).
// 🔴 **ונפילה-חזרה כשהיא כבויה:** אחרת דווקא במצב הלחוץ ביותר המסך היה נופל לזווית שאין
// לה דאטה — בדיוק התסריט ש-`spec.md §12` מזהיר ממנו *("בלי טיפול, המסך היה נופל בשקט")*.
export function defaultSortAngle(isUrgent, availability = {}) {
  if (isUrgent && isAngleAvailable('fastest', availability)) return 'fastest'
  return 'recommended'
}

// 🔴 **נעוצה קודמת לכל זווית** — הנעיצה היא שכבה 2 והזווית היא שכבה 4, וסדר-השכבות הוא
// ההכרעה. 🚧 מ6: הטבלה ריקה היום, ולכן בפועל אף אחת אינה נעוצה — אבל הסדר נכון מהיום.
// ⚠️ ושובר-השוויון הוא זה של הדירוג (`tieBreak`) ולא סדר-הקליטה: שתי מועמדות באותו מרחק
// היו מחליפות מקום בין רענונים, וזה נראה כמו מסך שמשנה את דעתו.
export function sortByAngle(candidates, angle) {
  const compare = COMPARATORS[angle] ?? COMPARATORS.recommended
  return [...(candidates ?? [])].sort(
    (a, b) =>
      Number(b.pinned) - Number(a.pinned) ||
      compare(a, b) ||
      String(a.tieBreak ?? '').localeCompare(String(b.tieBreak ?? '')),
  )
}
