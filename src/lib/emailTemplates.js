const DEFAULT_CONSEQUENCE = 'הפעולה שהמשתנה הזה מיועד לה לא תעבוד'

// שם-תבנית לא-מוכר (למשל `URL` כמו `קישור_בסיס_סקר_לקוחות`, שלא פותח עורך-תבנית בכלל) —
// אין לו חוזה, ולכן שום דבר לא נחסם על-ידי הפונקציה הזו. `TemplateEditor.jsx` (3.2) אחראית
// לא לפתוח את העורך על שורה כזו מלכתחילה.
export function templateSaveVerdict(name, body) {
  const contract = TEMPLATE_PLACEHOLDERS[name]
  if (!contract) {
    return { status: 'ok', missingRequired: [], missingOptional: [], unknown: [], message: '' }
  }

  const allowed = [...contract.required, ...contract.optional]
  // `findUnknownPlaceholders` סורקת את **התבנית**, לא את תוצאת-המילוי (אותה מלכודת-דמו
  // המתועדת ב-email.js) — כאן זה בדיוק המצב: `body` הוא תוכן-העורך הגולמי, לפני מילוי.
  const knownAsReplacements = Object.fromEntries(allowed.map((token) => [token, '']))
  const unknown = findUnknownPlaceholders(body, knownAsReplacements)

  const text = body ?? ''
  const missingRequired = contract.required.filter((token) => !text.includes(token))
  const missingOptional = contract.optional.filter((token) => !text.includes(token))

  // סדר-הבדיקה: חובה-חסרה קודם (ההודעה שלה הכי פעילה — "בלי X, Y") ואז לא-מוכר.
  // שני המצבים חוסמים באותה מידה; ההבדל הוא רק **איזו הודעה מוצגת** כשקורים יחד
  // (למשל שגיאת-כתיב בסוגריים שגם יצרה טוקן-לא-מוכר וגם "מחקה" בפועל טוקן-חובה).
  if (missingRequired.length > 0) {
    const token = missingRequired[0]
    const consequence = REQUIRED_CONSEQUENCES[name]?.[token] ?? DEFAULT_CONSEQUENCE
    return {
      status: 'blocked',
      missingRequired,
      missingOptional,
      unknown,
      message: `בלי ${token} ${consequence}`,
    }
  }

  if (unknown.length > 0) {
    return {
      status: 'blocked',
      missingRequired,
      missingOptional,
      unknown,
      message: `משתנה לא מוכר בתבנית: ${unknown.join(', ')}`,
    }
  }

  if (missingOptional.length > 0) {
    return {
      status: 'warning',
      missingRequired,
      missingOptional,
      unknown,
      message: `חסרים משתנים אופציונליים: ${missingOptional.join(', ')}`,
    }
  }

  return { status: 'ok', missingRequired: [], missingOptional: [], unknown: [], message: '' }
}
