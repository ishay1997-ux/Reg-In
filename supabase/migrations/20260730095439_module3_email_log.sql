-- why: עד עכשיו אין במערכת שום מקור-אמת לשאלה "האם המסמך הזה כבר נשלח ללקוח". ההגנות
--   מפני שליחה-כפולה שנבנו במסך (נעילת-כפתור · כפתור שהופך ל"נשלח ✓" · חלון-אישור) חיות
--   כולן ב-state של הקומפוננטה, ולכן **רענון-דף או משתמש שני מבטלים אותן לגמרי**. הצעת
--   מחיר שנשלחת ללקוח פעמיים היא נזק אמיתי מול לקוח, ולא תקלה פנימית.
--   הכרעת-ישי 30/07/2026: להקדים לכאן את ישות יומן-השליחות שהייתה רשומה כחוב של **מודול 10**
--   (‏🚧 מ10 ב-PROJECT_MASTER §6, "ישות יומן-שליחות") — בקשתו המפורשת, אחרי שהצגתי שזה
--   הפער היחיד מתוך שמונה שלא ניתן לסגור בקוד-לקוח.
--
-- ⚠️ תוספת מעבר לאפיון הקפוא: ל-C6 אין טבלה כזו (§6 מ10 מציין אותה כישות נדרשת בלי סכמה).
--   העיצוב כאן הוא שלנו, ונרשם ככזה ב-docs/db_roadmap.md §10 ובמדריך-המיקרו §9.
--
-- 🔑 החלטת-עיצוב מרכזית: הטבלה **גנרית ולא של הצעות-מחיר**. יש 6 תבניות-מייל ב-`params`
--   (הצעה #10 · זימון-משמרת #11 · משוב-לקוח #12 · חשבונית #13 · ביטול-משמרת #14 · דוח-שכר #20),
--   כלומר מודולים 4/8/11 ישלחו מיילים גם הם. טבלה בשם `quote_email_log` הייתה מזמינה שלוש
--   טבלאות-אחיות ושלוש העתקות של אותה לוגיקה. לכן: (entity_type, entity_id) פולימורפי.
--   ⚠️ המחיר המודע: אין FK אמיתי ל-`quotes` (אי-אפשר FK לטבלה משתנה), ולכן מחיקת-ישות לא
--   תגרור את שורות-היומן. זה **מקובל ואף רצוי** ביומן-שליחות: העובדה שנשלח מייל היא
--   היסטוריה שאין למחוק, ובפרויקט הזה ממילא אין מחיקה (§7.11 — מארכבים, לא מוחקים).
--
-- על מה זה משפיע: טבלה חדשה בלבד. אף טבלה קיימת אינה משתנה, אף עמודה אינה נוגעת.
-- הפיכוּת: מלאה (drop table) כל עוד לא נשלחו מיילים שנרשמו בה.

create table if not exists email_log (
  email_log_id bigint generated always as identity primary key,

  -- לאיזו ישות שייכת השליחה. ה-CHECK נפתח בכל מודול שמתחיל לשלוח — הוספת ערך היא
  -- מיגרציה של שורה אחת, וזה בכוונה: ערך חופשי היה מאפשר שגיאת-הקלדה שמייצרת "סוג" חדש בשקט.
  entity_type text not null check (entity_type in ('quote')),
  entity_id bigint not null,

  -- למי נשלח, ומה נשלח. `recipient` נשמר כטקסט ולא כ-FK ללקוח: הכתובת שנשלחה בפועל היא
  -- עובדה היסטורית, וכרטיס-הלקוח יכול להשתנות אחר-כך בלי לשנות את מה שקרה.
  recipient text not null,
  template_name text,
  subject text,

  -- 'sent' = ‏Make אישר שהמייל יצא (200 אחרי מודול-השליחה). 'failed' = כשל מדווח.
  -- ⚠️ אין ערך 'unknown' בכוונה: שורה נכתבת **רק** כשיש תשובה חד-משמעית מהשרת. מצב
  --   "לא ידוע" (פסק-זמן/נפילת-רשת) מטופל ב-UI ואינו נרשם כאן — יומן שמכיל "אולי נשלח"
  --   מפסיק להיות מקור-אמת לשאלה שבשבילה הוא נבנה.
  status text not null check (status in ('sent', 'failed')),
  error_message text,

  -- מי לחץ. מייל-המשתמש ולא user_id — אותה תבנית כמו `projects.owner_email`, וקריא ביומן
  -- גם אחרי שמשתמש הפך ל-inactive.
  sent_by_email text,

  created_at timestamptz not null default now()
);

-- שאילתת-העל של הטבלה: "האם/מתי נשלחה הישות הזאת". כל קריאה מה-UI היא בדיוק זו.
create index if not exists idx_email_log_entity on email_log (entity_type, entity_id, created_at desc);

-- ── RLS (§7.21, שער-המודול 'הצעות מחיר') ─────────────────────────────────────────────
-- קריאה למי שיש לו edit|view על הצעות-מחיר; **כתיבה — לאף אחד מהלקוח.** את שורות היומן
-- כותבת פונקציית-השרת (Edge Function) עם service-role, שעוקפת RLS במכוון: יומן שהדפדפן
-- יכול לכתוב אליו אינו ראיה, כי מי שמפברק בקשה יכול לרשום "נשלח" בלי שנשלח דבר.
-- ⚠️ כשמודולים 4/8/11 יתחילו לשלוח — כל אחד יוסיף policy-קריאה משלו לפי שער-המודול שלו,
--   בדיוק כמו שנעשה כאן; אין להרחיב את השער הזה ל'כל המחוברים'.
alter table email_log enable row level security;

create policy "email_log_select_quotes_module" on email_log for select to authenticated
  using (
    entity_type = 'quote'
    and exists (
      select 1 from permissions p
      where p.role_id = (select current_user_role_id())
        and p.module_id = (select module_id from modules where module_name = 'הצעות מחיר')
        and p.permission_level in ('edit', 'view')
    )
  );

comment on table email_log is
  'יומן שליחות מיילים — מקור-האמת ל"האם נשלח". גנרי לפי (entity_type, entity_id). נכתב ע"י Edge Function בלבד (service-role); הלקוח קורא ולא כותב. הוקדם ממודול 10 בהכרעת-ישי 30/07/2026.';
