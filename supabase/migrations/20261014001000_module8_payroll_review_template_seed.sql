-- =============================================================================
-- why: הסיכום האישי שנשלח לכל דיילת לפני ההפקה (§7.108) צריך תבנית משלו בהגדרות →
-- תבניות מייל. לא משתמשים בתבנית של רואה החשבון: קהל אחר, קישור אישי ומועד אחרון.
-- ארבעת המשתנים החובה: [שם_דיילת] · [חודש_דיווח_ושנה] · [לינק_בדיקת_שעות] ·
-- [מועד_אחרון_לתגובה]. הגוף — נוסח האפיון, עם תיקון מדריך ה-UX ("נשמח לתשובתך עד").
--
-- 🔑 param_type מועתק משורת תבנית_מייל_דוח_שכר (ולא נכתב כאן כקבוע) — כך התבנית החדשה
-- נופלת תמיד באותה קבוצה כמו אחותה. בעלות: 'מנהלת כספים ולקוחות', כמו תבנית רואה החשבון.
-- 🔑 אידמפוטנטי: on conflict do nothing — הרצה חוזרת לא דורסת גוף שהמנהלת כבר ערכה.
-- 🔴 שער כישלון רועש: אם אחת משתי שורות-המקור לא נמצאה, ה-insert היה מכניס 0 שורות בשקט.
-- =============================================================================

insert into public.params (param_name, param_type, param_value, owner_role_id)
select 'תבנית_מייל_סיכום_שעות_דיילת',
       src.param_type,
       $tpl$שלום [שם_דיילת],

סיכום השעות שלך לחודש [חודש_דיווח_ושנה] מוכן לבדיקה.
אפשר לאשר את הנתונים או לדווח על טעות בקישור:
[לינק_בדיקת_שעות]

נשמח לתשובתך עד [מועד_אחרון_לתגובה].$tpl$,
       (select r.role_id from public.roles r where r.role_name = 'מנהלת כספים ולקוחות')
  from public.params src
 where src.param_name = 'תבנית_מייל_דוח_שכר'
on conflict (param_name) do nothing;

do $$
declare v_row public.params;
begin
  select * into v_row from public.params where param_name = 'תבנית_מייל_סיכום_שעות_דיילת';
  if v_row.param_id is null then
    raise exception 'מ8 מיגרציה 10: שורת התבנית לא נוצרה (תבנית_מייל_דוח_שכר חסרה?) — המיגרציה בוטלה';
  end if;
  if v_row.owner_role_id is null then
    raise exception 'מ8 מיגרציה 10: התפקיד "מנהלת כספים ולקוחות" לא נמצא — המיגרציה בוטלה';
  end if;
end $$;
