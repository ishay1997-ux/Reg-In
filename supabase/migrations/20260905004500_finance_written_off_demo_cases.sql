update public.projects
   set payment_date = null
 where project_id in (823, 1108);

update public.project_finance
   set written_off = true,
       written_off_reason = case
         when project_id = 823 then 'מחלוקת מסחרית בעקבות תלונת איכות תגים ותפקוד צוות — הוסכם על ביטול הדרישה והכרזה כחוב אבוד'
         when project_id = 1108 then 'הלקוח נקלע לחדלות פירעון ולהקפאת הליכים — החוב הוכרז כאבוד לאחר מיצוי הליכי גבייה משפטיים'
       end,
       final_profit = case
         when project_id = 823 then -5888.90
         when project_id = 1108 then -7130.40
       end
 where project_id in (823, 1108);
