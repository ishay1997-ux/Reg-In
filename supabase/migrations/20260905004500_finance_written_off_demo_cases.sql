-- מיגרציה: סימון שני מקרי חוב-אבוד היסטוריים (823, 1108) להדגמת תרחישי קצה ומנגנון סגירה ללא תשלום
-- =============================================================================
-- פרויקט 823 (2024-01-22): סכסוך איכות מסחרי על תגים שלא נגבה (ציון 1)
-- פרויקט 1108 (2025-04-02): כניסת לקוח להקפאת הליכים / חדלות פירעון (ציון 2)
--
-- מהלך זה מדגים את שער-הסגירה של מודול 8 ("הסתיים — לא שולם"),
-- ומעמיד את שיעור הגבייה (Collection Rate) על 99.7% אמין וריאלי לכנס.
