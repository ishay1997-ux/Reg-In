-- 🐛 **הפגם, ואיך נמצא.** בודק-האפיון של פזה 2 (27/08) מצא ש-`uploadSalaryReportFile`
--    ‏(`src/modules/08_finance/api.js`) **אינו יכול להצליח לעולם**. אומת חי באותו ערב:
--
--      finance → allowed_mime_types = {application/pdf, image/jpeg, image/png}
--
--    ‏אין ‏xlsx ברשימה ⇒ ‏Storage דוחה את ההעלאה ⇒ ‏`report_file_url` נשאר NULL.
--
-- 💥 **מה מת בשקט בגלל זה** — שלוש הבטחות מפורשות של כרטיס-P4:
--      ‏① "היסטוריית-הדוחות מציגה כל מה שנשלח, עם הורדה" — אין קובץ להוריד.
--      ‏② "שליחה-חוזרת מההיסטוריה" — אין ממה לשלוח שוב.
--      ‏③ ‏§7.68 — ‏snapshot-ההוכחה של מה-נשלח-לרו"ח אינו נשמר כלל.
--
-- 🔑 **ולמה זו אינה "הכרעה מוצרית שמישהו קיבל", אלא חור:** המיגרציה של מ6 שיצרה את
--    ה-bucket נושאת על שורת-`finance` את ההערה **"לא הוכרע (M8 יחליט)"** — כלומר רשימת
--    ה-MIME הייתה **מציין-מקום מוצהר**, ומ8 הוא שאמור היה להכריע. ‏ה13 הכריע רק את
--    ה**גודל** ("‏bucket `finance` נשאר 10MB"), ו-ה4 מחייב **xlsx בלבד** לדוח-השכר.
--    ⇒ הוספת ה-MIME היא השלמת ההכרעה שמ8 חייב, לא שינוי של הכרעה קיימת.
--
-- ⚠️ **מה המיגרציה הזו לא עושה:** אינה נוגעת בגודל (10MB), אינה נוגעת בארבע המדיניות,
--    ואינה הופכת את ה-bucket לציבורי. הוא נשאר `public=false`.
-- =============================================================================

update storage.buckets
   set allowed_mime_types = array[
         'application/pdf',
         'image/jpeg',
         'image/png',
         -- ‏xlsx — הפורמט שה4 מחייב לדוח-השכר.
         'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet'
       ]
 where id = 'finance';

