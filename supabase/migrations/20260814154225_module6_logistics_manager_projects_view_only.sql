-- מודול 6 — הורדת מנהלת הלוגיסטיקה ל-view על 'פרויקטים'
-- הכרעת-ישי 14/08/2026: "להוריד אותה לצפייה בלבד".
--
-- why: ㉘ קובע שה-RPC הוא יחידת-ההרשאה => 'פרויקטים' ב-edit פירושו שהיא רשאית לבטל
--   פרויקט, להזיז תאריך ולשנות תכולה. §4.4 במדריך אומר שהיא לא אמורה לראות את הכפתורים
--   האלה — והסתרת כפתור אינה אכיפה. שניהם לא יכולים להתקיים.
--   (סריקת-האדוות של 14/08 העלתה את זה כממצא מספר 1: "המסד מאפשר לה, רק המסך מסתיר".)
--
-- נמדד לפני השינוי: ה-policy היחידה שנוקבת ב-'פרויקטים' היא projects_select_by_permission
--   ו-view מספיק לה; אפס פונקציות חיות דורשות edit דווקא; ועבודת הלוגיסטיקה שלה רצה על
--   'לוגיסטיקה'=edit שאינו נוגע כאן. => היא ממשיכה לראות את כרטיס-הפרויקט ואת לשונית
--   הלוגיסטיקה, ומאבדת רק את מה שהמדריך ממילא הצהיר שאין לה.
-- אחרי: רק מנכ"ל ומנהלת פרויקטים מחזיקים edit על 'פרויקטים'.
-- הפיכוּת: מלאה — update אחד חזרה ל-'edit'.

update public.permissions p
   set permission_level = 'view'
 where p.role_id   = (select r.role_id from public.roles r where r.role_name = 'מנהלת לוגיסטיקה')
   and p.module_id = (select m.module_id from public.modules m where m.module_name = 'פרויקטים')
   and p.permission_level = 'edit';
