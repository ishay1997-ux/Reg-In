-- שער רועש: בלי שורת-התפקיד, ה-select למטה היה מחזיר NULL וארבעת הפרמטרים היו נולדים
-- בלי בעלים — כלומר בלי שהמנכ"ל יוכל לערוך אותם, ובלי שאיש יראה שמשהו השתבש.
do $$
begin
  if not exists (select 1 from public.roles where role_name = 'מנכ"ל') then
    raise exception 'לא נמצאה שורת-התפקיד מנכ"ל בטבלת roles — ארבעת הפרמטרים היו נשמרים בלי בעלים.'
      using errcode = 'P0001';
  end if;
end $$;

insert into public.params (param_name, param_value, param_type, owner_role_id)
select v.param_name,
       v.param_value,
       'control_alerts',
       (select r.role_id from public.roles r where r.role_name = 'מנכ"ל')
  from (values
    ('מכפיל_מרווח_מתרחק',   '1.5'),
    ('סף_סטיית_תקציב_אחוז', '15'),
    ('מקדם_אמינות_אדום',    '0.87'),
    ('מקדם_אמינות_ענבר',    '0.95')
  ) as v(param_name, param_value)
on conflict (param_name) do nothing;
