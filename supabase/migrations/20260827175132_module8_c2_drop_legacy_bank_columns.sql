-- 🔴 **השומר `updated_at` הוא לב העניין, ולא קישוט.** חלון-הזמן שבין מיגרציה C
-- לפריסה רץ **לשני כיוונים הפוכים**:
--   • **לפני** הפריסה — ‏`origin/main` כתב לעמודות **ההורה**; שורת-ילדה של
--     דיילת שנוצרה או נערכה אז חסרה או מתיישנת ⇒ צריך להעתיק.
--   • **אחרי** הפריסה — הקוד החדש כותב **רק לילדה** (`splitBankFields`) ⇒
--     העתקה לא-מסויגת הייתה **דורסת נתונים טריים בישנים**. אותו אובדן-מידע
--     שההעתקה נועדה למנוע, רק הפוך — ומגיע כמספרי-בנק שגויים בדוח לרו"ח.
-- ⇒ מעתיקים **רק** כשההורה באמת חדש יותר מהילדה. שתי הטבלאות נושאות
--   ‏`updated_at` שמתוחזק ע"י `extensions.moddatetime`.
--
-- 📏 **נמדד לפני הכתיבה (27/08/2026 17:4X):** ‏26 דיילות · 26 שורות-ילדה ·
--    **0 הורים בלי ילדה** · **0 הורים חדשים-מהילדה** · **0 פערי-ערכים**.
--    ⇒ הבלוק הזה צפוי לגעת ב-**0 שורות** היום. הוא נשאר בכל זאת, כי מיגרציה
--    היא **רשומה** ולא סקריפט חד-פעמי: מי שיריץ את הרצף הזה על סביבה אחרת,
--    או אחרי חלון ארוך יותר, חייב את הרשת. 🔑 **ואותה מדידה מראה למה השומר
--    נחוץ:** כל 26 שורות-הילדה **חדשות** מההורה שלהן ⇒ בלי `where`, ההעתקה
--    הייתה נוגעת בכל 26 ומושכת אותן אחורה למקור הישן.
insert into hostess_bank_details (hostess_id, bank_name, bank_branch, bank_account)
select h.hostess_id, h.bank_name, h.bank_branch, h.bank_account
  from hostesses h
 where coalesce(h.bank_name, h.bank_branch, h.bank_account) is not null
on conflict (hostess_id) do update
   set bank_name    = excluded.bank_name,
       bank_branch  = excluded.bank_branch,
       bank_account = excluded.bank_account
 where hostess_bank_details.updated_at
       < (select h2.updated_at from hostesses h2
           where h2.hostess_id = hostess_bank_details.hostess_id);
-- ⚠️ ה-`where` יושב על **פעולת-הקונפליקט**, ולכן הוא רואה את השורה הקיימת
--    (`hostess_bank_details.*`) ואת המועמדת (`excluded.*`). ‏`excluded` **אינו**
--    נושא את `updated_at` של ההורה — הוא לא ב-INSERT — ולכן ההשוואה חוזרת
--    ל-`hostesses` בתת-שאילתה מפורשת. זו הנקודה שהחוזה ב-§8.4 השאיר במפורש
--    "להכריע מול ה-DDL החי", וכך הוכרעה.


