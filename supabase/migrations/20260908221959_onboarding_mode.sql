-- מצב הטמעה · מיגרציה עצמאית — עמודת-רמה + מדיניות-מנכ"ל רביעית על notification_preferences
-- =============================================================================
-- **למה:** הכרעה 28 (`docs/specs/module_11_reports/processes-approved.md` §🗳️) — מתג
-- פר-משתמשת שמדליק שכבת-הסבר מעל המסכים. 28⑭ (07/09/2026): העמודה נולדת כ**רמה** `0/1/2`
-- ולא כבוליאני — 0 נקי · 1 מכוון · 2 מודרך — כדי שלא תידרש מיגרציה שנייה כשרמה 1 תיכתב
-- (בוליאני→רמה אחרי ההחלה = מיגרציה + חוזה `<Hint>` + שני מתגים + כל מפתח-קופי; עכשיו = אפס).
-- הלילה (08/09/2026) בונה 0 ו-2 בלבד; המתג במסכים ממפה כן/לא ל-0/2.
--
-- **למה מיגרציה עצמאית ולא של מ11** (28⑤, סטייה מוצהרת בהכרעת-ישי 07/09 05:1X): מ11 טרם
-- נבנה ואין לו מיגרציה לצרף אליה; המתנה לו הייתה חוסמת את שכתוב-הטקסטים.
--
-- **הטיפוס:** `integer` ולא `smallint` — אפס `smallint` בריפו, כל מספר שלם הוא `integer`/`bigint`
-- (סבב-עיניים-טריות 07/09 17:3X). אילוץ **בשם** — סגנון-הריפו למגבלות שנוספות אחר-כך.
-- **ברירת-המחדל 0 (כבוי)** — הכרעת-ישי 28⑫(א) *"1. בסדר"*, עקבי עם כלל-הטבלה הקיים
-- *"אין שורה = הכל כבוי"*: משתמשת בלי שורה היא רמה 0, בדיוק כמו שורה עם 0.
--
-- **המדיניות הרביעית** (28⑫(ב) *"2. בסדר"* · 28⑭(ב)): שלוש הקיימות הן עצמי-בלבד
-- (`email = auth.email()`), ולכן **המנכ"ל לא יכול לכתוב — וגם לא לקרוא — את השורה של אחרת**,
-- ודלת-ניהול-המשתמשים של 28⑨ לא הייתה קיימת בלעדיה. `for all` ולא `for update`: הוא גם
-- **קורא** את הרמה של כל משתמשת כדי לצייר את המתג בטבלה, וגם **יוצר** שורה למי שאין לה.
-- התקדים המדויק: `users_write_ceo_only` (`docs/schema.sql` §4) — אותו פרדיקט, עטוף
-- ב-`(select …)` לפי תבנית §7.21. הערך `'מנכ"ל'` הוא ערך-דאטה ב-`roles`, לא טקסט-ממשק.
--
-- **הפיכוּת:** `drop policy notification_preferences_ceo_all` + `alter table … drop column
-- onboarding_mode` (האילוץ וההערה נופלים עם העמודה). **כלל-הפריסה:** תוספת טהורה
-- (`add column` עם default · `create policy`) — הקוד הישן אינו יודע שהן קיימות ואינו נשבר.
-- =============================================================================

alter table public.notification_preferences
  add column onboarding_mode integer not null default 0;

alter table public.notification_preferences
  add constraint notification_preferences_onboarding_mode_check
  check (onboarding_mode between 0 and 2);

comment on column public.notification_preferences.onboarding_mode is
  'רמת מצב-ההטמעה של המשתמשת: 0 נקי (ברירת-מחדל, אין שורה = 0) · 1 מכוון (מונח · מקור-מספר · נימוק-סידור, שורה לכל אחד — טרם נכתב) · 2 מודרך (ההסבר המלא). הכרעה 28⑭, 07/09/2026.';

-- הערת-הטבלה הקודמת דיברה על "שני מתגים"; עכשיו יש שתי העדפות-התראה ורמת-הטמעה אחת.
comment on table public.notification_preferences is
  'העדפות פר-משתמשת: שתי העדפות-התראה (מודול 9 שומר, מודול 10 שולח) ורמת מצב-ההטמעה (onboarding_mode). אין שורה = הכל כבוי ורמה 0. SMS: העמודה קיימת, הערוץ לא (R-4).';

-- מדיניות רביעית — המנכ"ל קורא/כותב כל שורה (דלת ניהול-המשתמשים, הכרעה 28⑨).
create policy notification_preferences_ceo_all on public.notification_preferences
  for all to authenticated
  using (
    (select current_user_role_id()) = (select role_id from public.roles where role_name = 'מנכ"ל')
  )
  with check (
    (select current_user_role_id()) = (select role_id from public.roles where role_name = 'מנכ"ל')
  );
