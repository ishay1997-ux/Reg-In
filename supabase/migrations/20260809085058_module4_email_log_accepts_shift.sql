-- ============================================================
-- מודול 4 — מיגרציה 0: `email_log` מקבל גם `'shift'`, ומקבל policy-קריאה משלו
-- ============================================================
-- למה עכשיו, ולמה **לפני** ששולחים ולו זימון-משמרת אחד:
-- ‏`send-email` נכשלת בשקט על היומן — היא מחזירה `{ok:true, log_failed:true}` וממשיכה,
-- כי המייל **כבר יצא** ולומר "נכשל" היה גורר שליחה כפולה לדיילת. המשמעות: אם ה-CHECK
-- עדיין אינו מכיר `'shift'`, השליחה הראשונה תצליח **והיומן יישאר ריק** — כלומר ההגנה
-- מפני שליחה-כפולה של מודול 4 לא תתקיים מהיום הראשון, בלי שום שגיאה שמישהו יראה.
--
-- 🚫 **ולא מרחיבים את ה-policy הקיימת של ההצעות ל"כל המחוברים".** ‏`db_roadmap` A-20 קבע
-- זאת כהודעה-קדימה למ4/מ8/מ11 עוד כשהטבלה נולדה: כל מודול מוסיף **ערך אחד** ו-**policy
-- משלו**. הרחבה גורפת הייתה חושפת את יומן-ההצעות למנהלת הגיוס ואת יומן-הדיילות למנהלת
-- הכספים — שתיהן חסומות זו במודול של זו לפי מטריצת ההרשאות (§3).
--
-- 🔁 **הפיכוּת:** ה-policy נמחקת בשורה אחת. ה-CHECK חוזר לצורתו הקודמת **כל עוד אין שורות
-- `'shift'`** — מרגע שנשלח זימון ראשון, צמצום חוזר יידרוש קודם מחיקת-שורות, ובפרויקט הזה
-- לא מוחקים היסטוריה (§7.11). אין כאן מחיקת עמודה, שינוי-טיפוס או נגיעה בדאטה קיימת.

-- ⚠️ ה-CHECK הקיים נוצר עם ערך יחיד ולכן Postgres כתב אותו כשוויון (`= 'quote'`) ולא כ-IN.
-- מוחקים ויוצרים מחדש בשם **זהה**, כדי שהשם יישאר צפוי למי שיחפש אותו בעתיד.
alter table email_log drop constraint email_log_entity_type_check;

alter table email_log
  add constraint email_log_entity_type_check
  check (entity_type in ('quote', 'shift'));

-- תבנית §7.21 בדיוק כמו ה-policy של ההצעות (מיגרציה `20260730095439`), כולל עטיפת
-- ‏`(select …)` — בלעדיה Postgres מריץ את תת-השאילתה פר-שורה (initplan) והקריאה מתנוונת.
-- ‏`edit` **וגם** `view`: מנהלת הפרויקטים היא `view` על 'דיילות' לפי §3, והיומן הוא מידע
-- לצפייה. הכתיבה נשארת ל-service-role בלבד — אין policy-כתיבה, ובכוונה: יומן שהדפדפן
-- יכול לכתוב אליו אינו ראיה.
create policy "email_log_select_shifts_module" on email_log for select to authenticated
  using (entity_type = 'shift' and exists (select 1 from permissions p
    where p.role_id = (select current_user_role_id())
      and p.module_id = (select module_id from modules where module_name = 'דיילות')
      and p.permission_level in ('edit', 'view')));
