-- ‏מיגרציה 6 של מודול 3 — סיבת-דחייה שמינית: 'נפתחה בטעות'
--
-- ‏why-first: במערכת אין מחיקה בשום מקום (משתמשים ולקוחות מארכבים, §7.11), ולכן הצעה
-- שנפתחה בטעות יכולה רק **להידחות** — ואז היא נשארת לנצח בסטטיסטיקה ומורידה את
-- שיעור-האישור. שיעור-אישור שמושפע מטעויות-הקלדה אינו מדד עסקי אלא רעש.
--
-- ‏הכרעת-ישי 29/07/2026: הפתרון הוא **סיבה שמינית שמוחרגת מהמכנה של שיעור-האישור**,
-- ולא מחיקת-הצעה. שלוש סיבות: (א) היא שומרת על מוסכמת "אין מחיקה" — חריג יחיד מלמד
-- משתמשים לצפות למחיקה גם היכן שהיא אסורה; (ב) היא עולה שורת-CHECK אחת במקום מסך,
-- הרשאה וחלון-וידוא; (ג) היא משמרת את העובדה שההצעה התקיימה ובוטלה.
--
-- ‏זהו **תיקון מפורש להכרעת §7.82/F2 של ישי עצמו מ-12/07/2026** ("בדיוק 7 ערכים") —
-- ה-write-back ל-PROJECT_MASTER §7 נעשה באותו סשן (כלל ברזל 13א).
--
-- ‏על מה זה משפיע: טבלת quotes בלבד. שום שורה קיימת אינה משתנה — האילוץ מורחב ולא מוקטן.
-- ‏הפיכוּת: מלאה כל עוד אף הצעה לא נדחתה בסיבה החדשה (מיגרציית-חזרה מחזירה ל-7 ערכים).
-- ‏ההחרגה מחישוב שיעור-האישור עצמה חיה בקוד (`NON_LOSS_REJECTION_REASONS` ב-src/lib/quotes.js)
-- ולא ב-DB: זו שאלת-תצוגה, וה-DB אינו מחשב מדדים.

alter table public.quotes
  drop constraint quotes_rejection_reason_check;

alter table public.quotes
  add constraint quotes_rejection_reason_check
  check (
    rejection_reason is null
    or rejection_reason = any (array[
      'מחיר'::text,
      'חוסר זמינות/לו"ז'::text,
      'נבחר מתחרה'::text,
      'תקציב לקוח'::text,
      'האירוע בוטל אצל הלקוח'::text,
      'פג תוקף'::text,
      'נפתחה בטעות'::text,
      'אחר'::text
    ])
  );
