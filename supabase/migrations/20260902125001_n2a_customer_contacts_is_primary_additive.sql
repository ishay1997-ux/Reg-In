-- ── ① הדגל ────────────────────────────────────────────────────────────────────
-- ‏`default false` ולא `true`: שורה חדשה שנוצרת מהמסך היא **איש-קשר נוסף** אלא אם נאמר
-- אחרת במפורש. ברירת-מחדל `true` הייתה מייצרת ראשי-שני בכל הוספה ונחסמת ע"י האינדקס
-- שלמטה — כלומר שגיאה במקום התנהגות.
alter table public.customer_contacts
  add column if not exists is_primary boolean not null default false;

comment on column public.customer_contacts.is_primary is
  'איש-הקשר הראשי של הלקוח. בדיוק אחד לכל לקוח (אינדקס חלקי ייחודי). N2, 02/09/2026.';

-- ── ② קידום הראשי הקיים משלוש עמודות-האב לשורת-בת ─────────────────────────────
-- 🔑 **`contact_id` הוא `generated always as identity`** (נמדד) ⇒ **אסור לספק אותו**;
-- אספקה מפורשת הייתה נכשלת ב-`428C9`.
-- ⚠️ **`btrim` ולא `is not null` בלבד:** ‏`contact_name` הוא `not null` בטבלת-הבת, ולקוח
-- שנשמר עם שם-ריק *(מחרוזת ריקה עוברת `not null`)* היה מפיל את המיגרציה כולה. **נמדד:
-- כל 9 תקינים** — הבדיקה כאן היא נגד מצב עתידי, לא נגד הנתונים של היום.
-- 🚫 **ואין `on conflict`:** הטבלה ריקה, ואין אילוץ שאפשר להתנגש בו. `on conflict do nothing`
-- היה מסתיר כישלון-אמיתי אם ההנחה הזו תשתנה.
insert into public.customer_contacts (customer_id, contact_name, phone, email, is_primary)
select c.customer_id, btrim(c.contact_name), c.phone, c.email, true
  from public.customers c
 where c.contact_name is not null
   and btrim(c.contact_name) <> '';

-- ── ③ בדיוק אחד ראשי לכל לקוח ─────────────────────────────────────────────────
-- אינדקס **חלקי** ייחודי: הוא אוכף "לא יותר מאחד", ואינו יכול לאכוף "לפחות אחד".
-- 🔴 **וזה מכוון, לא פשרה:** "לפחות אחד" הוא כלל-מחזור-חיים (אי-אפשר למחוק את האחרון),
-- ומקומו ב-RPC שמוחק — שם אפשר להחזיר את המשפט שישי ניסח. אילוץ-מסד היה יכול רק
-- לזרוק שגיאה גנרית, ובאמצע מחיקה זה נראה למשתמשת כתקלה ולא ככלל.
create unique index if not exists customer_contacts_one_primary_per_customer
  on public.customer_contacts (customer_id)
  where is_primary;
