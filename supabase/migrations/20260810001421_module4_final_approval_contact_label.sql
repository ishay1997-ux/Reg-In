-- מודול 4 · מיגרציה H — **תיוג איש-הקשר במייל האישור-הסופי.**
--
-- 🔴 **הבעיה, במילים של מה שהדיילת קוראת:** התבנית `תבנית_אישור_סופי_שיבוץ` מקודדת בגוף
-- הטקסט את המילים *"מנהלת הפרויקט -"* לפני ה-placeholder של השם. ‏`local-2` (הכרעת-ישי
-- 08/08/2026, ובעקבות `processes-approved.md §ב5`) קובע ש**איש-הקשר בשטח הוא אחראית
-- המשמרת כשהיא מסומנת**, ורק בהיעדרה מנהלת הפרויקט. ⇒ ברגע שמסומנת אחראית משמרת,
-- המייל מציג אותה בתפקיד שאינו שלה — **בפני הדיילות האחרות שאמורות לפנות אליה בשטח.**
--
-- 🔑 **למה שינוי-טקסט ולא placeholder חדש:** ‏`spec.md §12` רשם במפורש ש*"לתבנית אין
-- placeholder עבורה בכלל"*, ו-§7.89 האציל *"כל placeholder מוכרע לגופו"*. הוספת
-- placeholder שביעי הייתה מחייבת את **כל** מסלולי-השליחה לדעת עליו; הסרת שתי המילים
-- הקשיחות מעבירה את התפקיד **אל תוך הערך**, וכך אותו שדה משרת את שני המקרים בלי
-- שהמנוע יצטרך לדעת מי מהם.
--
-- **מה משתנה בפועל — שורה אחת בתוך הטקסט:**
--   לפני:  איש קשר בשטח: מנהלת הפרויקט -[שם_מנהלת_פרויקט], טלפון: [טלפון_מנהלת_פרויקט]
--   אחרי:  איש קשר בשטח: [שם_מנהלת_פרויקט], טלפון: [טלפון_מנהלת_פרויקט]
-- ‏**שמות ה-placeholders אינם משתנים** — הקוד ב-`src/lib/shiftEmails.js` ממשיך למלא את
-- אותם שני שדות, ולכן אין כאן שינוי-חוזה מול המנוע.
--
-- 🔒 **היקף:** שורה אחת בטבלת `params`. **אין DDL, אין RLS, אין טריגר, אין טבלה חדשה.**
-- ⚠️ **הפיכוּת: מלאה** — מיגרציית-תיקון קדימה שמחזירה את שתי המילים משחזרת את המצב
-- הקודם בדיוק. **ומה שאינו הפיך: מיילים שכבר יצאו** — הם נשארים כפי שנשלחו, וזה נכון.
--
-- 🚫 **מה המיגרציה הזו במפורש אינה עושה:** אינה נוגעת בארבע תבניות-הדיילות האחרות,
-- ואינה משנה את הכלל **מי** איש-הקשר — הכלל כבר ממומש בקוד (`resolveShiftContact`).

update public.params
set param_value = replace(
      param_value,
      'איש קשר בשטח: מנהלת הפרויקט -[שם_מנהלת_פרויקט]',
      'איש קשר בשטח: [שם_מנהלת_פרויקט]'
    )
where param_name = 'תבנית_אישור_סופי_שיבוץ'
  -- ⚠️ **מותנה בקיום המחרוזת המדויקת**: אם התבנית כבר תוקנה ידנית או שונתה, המיגרציה
  -- לא נוגעת בה — עדיף שלא תעשה כלום מאשר שתחתוך טקסט שמישהו כבר שינה.
  and param_value like '%איש קשר בשטח: מנהלת הפרויקט -[שם_מנהלת_פרויקט]%';
