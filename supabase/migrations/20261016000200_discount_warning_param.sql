do $$
begin
  if not exists (select 1 from public.roles where role_name = 'מנהלת כספים ולקוחות') then
    raise exception 'לא נמצאה שורת-התפקיד "מנהלת כספים ולקוחות" בטבלת roles — הפרמטר היה נשמר בלי בעלים.'
      using errcode = 'P0001';
  end if;
end $$;

insert into public.params (param_name, param_value, param_type, owner_role_id)
select 'סף_אזהרת_הנחה_אחוז',
       '30',
       'control_alerts',
       (select r.role_id from public.roles r where r.role_name = 'מנהלת כספים ולקוחות')
on conflict (param_name) do nothing;
