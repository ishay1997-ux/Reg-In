-- למה המיגרציה הזו קיימת: תיקון-דאטה אמיתי, לא seed.
--
-- projects.customer_name הוא snapshot שנכתב פעם אחת ע"י approve_quote_and_create_project
-- בזמן-האישור (schema.sql, בלוק "מודול 4 — לקוח נעלם"), ואינו מתעדכן רטרואקטיבית כששם-הלקוח
-- משתנה אחרי מכן. שלושה פרויקטים (#3, #7, #8) נוצרו לפני שתוקן שם-הלקוח "מדיטק פתרונות בע"מ"
-- (הוסרה ממנו התווית "[דמו]" ב-12/08/2026, ר' scripts/demo-seed.mjs) — ולכן עדיין נשאו את השם
-- הישן, גלוי במסך "מעקב פניות ושיבוצים" של מודול 4. נתפס ברהרסל-הדגמה חי, נדחה להכרעת-ישי
-- (כתיבה ל-projects דורשת עקיפת RLS), ואושר על-ידו 12/08/2026 ("תקן את שלושת התמונות הקפואות").
--
-- מה זה עושה: backfill-UPDATE יחיד, באותה צורה בדיוק כמו ה-backfill המקורי שמילא את העמודה
-- הזו לראשונה (schema.sql). מכוון ל**כל** פרויקט שה-snapshot שלו סטה מהשם הנוכחי של הלקוח —
-- לא רק לשלושת ה-IDs הידועים היום — כדי שהתיקון יהיה כללי ולא ילקט תקלות דומות בעתיד בשקט.
-- אינו נוגע בשום עמודה/טבלה/RLS/פונקציה. אין דרישת-הרשאה מיוחדת (מריץ כמיגרציה, לא כ-RPC).
--
-- הפיכות: מלאה ומיידית — הרצה חוזרת של אותו UPDATE בכל עת מחזירה את הסנכרון, ואין מחיקת-דאטה.

update public.projects p
   set customer_name = c.company_name
  from public.customers c
 where c.customer_id = p.customer_id
   and p.customer_name is distinct from c.company_name;
